struct Code {
    const char* bits; // '0'/'1', spaces ignored; a trailing 's' is a sign bit (value negated when 1)
    int value;
};

// Parses a code string into (bits, length, has_sign).
struct ParsedCode {
    u32 code = 0;
    int len = 0;
    bool sign = false;
};

ParsedCode parse_code(const char* s) {
    ParsedCode p;
    for (; *s; ++s) {
        if (*s == ' ') continue;
        if (*s == 's') {
            p.sign = true;
            continue;
        }
        p.code = (p.code << 1) | u32(*s == '1');
        ++p.len;
    }
    return p;
}

void fill(std::vector<VlcEntry>& lut, int bits, u32 code, int len, int value) {
    if (len > bits) throw std::logic_error("VLC code longer than table");
    u32 first = code << (bits - len), count = 1u << (bits - len);
    for (u32 i = 0; i < count; ++i) {
        VlcEntry& e = lut[first + i];
        if (e.len) throw std::logic_error("overlapping VLC codes");
        e.value = s16(value);
        e.len = u8(len);
    }
}

VlcTable build(int bits, std::initializer_list<Code> codes) {
    VlcTable t;
    t.bits = bits;
    t.lut.resize(size_t(1) << bits);
    for (const Code& c : codes) {
        ParsedCode p = parse_code(c.bits);
        if (p.sign) {
            fill(t.lut, bits, p.code << 1, p.len + 1, c.value);
            fill(t.lut, bits, (p.code << 1) | 1, p.len + 1, -c.value);
        } else {
            fill(t.lut, bits, p.code, p.len, c.value);
        }
    }
    return t;
}

struct DctCode {
    const char* bits; // without the sign bit
    u8 run, level;
};

void dct_fill(DctTable& t, const DctCode& c) {
    ParsedCode p = parse_code(c.bits);
    DctEntry e{c.run, c.level, u8(p.len)};
    u32 v16 = p.code << (16 - p.len); // code left-aligned in 16 bits
    if (v16 >= 1024) {
        // Short table: indexed by the top 10 bits.
        if (p.len > 10) throw std::logic_error("DCT code too long for the short table");
        u32 first = p.code << (10 - p.len), count = 1u << (10 - p.len);
        for (u32 i = 0; i < count; ++i) {
            if (t.short_codes[first + i].len) throw std::logic_error("overlapping DCT codes");
            t.short_codes[first + i] = e;
        }
    } else {
        // Six leading zeros: long table, indexed by the whole 16-bit peek.
        u32 count = 1u << (16 - p.len);
        for (u32 i = 0; i < count; ++i) {
            if (t.long_codes[v16 + i].len) throw std::logic_error("overlapping DCT codes");
            t.long_codes[v16 + i] = e;
        }
    }
}

